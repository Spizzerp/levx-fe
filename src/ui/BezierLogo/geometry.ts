/**
 * Cubic Bezier segments defining the logo silhouette.
 *
 * Traced from the source SVG in Inkscape and normalized into a symmetric
 * coordinate space roughly [-1, 1] × [-1, 1], centered on the full logo
 * (bracket + X together).
 *
 * Each entry is a flat array of 8 numbers: [P0.x, P0.y, P1.x, P1.y,
 * P2.x, P2.y, P3.x, P3.y], representing a single cubic Bezier segment.
 *
 * The two shapes are exported separately so the renderer can bake each
 * one into its own SDF texture and translate them independently for the
 * split-morph intro animation.
 */

export type CubicSegment = readonly [
  number,
  number, // P0
  number,
  number, // P1 (control)
  number,
  number, // P2 (control)
  number,
  number, // P3
]

